def to_jsonable(obj):
    """Recursively convert numpy scalars/arrays (which sneak in via pandas
    columns and CSV-derived dicts) into native Python types that FastAPI's
    default JSON encoder can serialize."""
    if isinstance(obj, dict):
        return {k: to_jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [to_jsonable(v) for v in obj]
    if isinstance(obj, np.generic):
        return obj.item()
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    return obj


def run_full_pipeline(resume_text: str, jd_text: str, level_hint: str = "",
                       max_hours: float = 200.0, max_budget: float = 500.0) -> dict:
    resume_skills = extract_resume_skills(resume_text)
    jd_skills = extract_jd_skills(jd_text, level_hint=level_hint)

    gap_report = analyzer.analyze(resume_skills, jd_skills)
    rec_report = recommender.recommend(gap_report["gaps"], resume_skills,
                                        max_hours=max_hours, max_budget=max_budget)

    return {
        "resume_skills": resume_skills,
        "jd_skills": jd_skills,
        "gap_analysis": gap_report,
        "learning_path": rec_report,
        "meta": {
            "n_resume_skills_found": len(resume_skills),
            "n_jd_skills_found": len(jd_skills),
        },
    }


